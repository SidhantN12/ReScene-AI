def _lab_color_transfer(
    source: np.ndarray,
    reference: np.ndarray,
    chroma_strength: float,
    l_strength: float = 0.10,
) -> np.ndarray:
    """Reinhard per-channel mean+std transfer in CIE LAB colour space.

    Luminance (L) is shifted only slightly so the room's natural lighting is
    preserved.  Chroma (A, B) is shifted more strongly to apply the style palette.
    This avoids the "muddy / colour-cast" artefact of full equal-strength transfer.
    """
    src_lab = cv2.cvtColor(source, cv2.COLOR_RGB2LAB).astype(np.float32)

    ref_rs = cv2.resize(reference, (source.shape[1], source.shape[0]),
                        interpolation=cv2.INTER_AREA)
    ref_lab = cv2.cvtColor(ref_rs, cv2.COLOR_RGB2LAB).astype(np.float32)

    # Per-channel strengths: L=luminance barely touched, A/B=chroma fully shifted
    strengths = [l_strength, chroma_strength, chroma_strength]

    result = src_lab.copy()
    for c, s in enumerate(strengths):
        src_mu, src_sd = src_lab[:, :, c].mean(), src_lab[:, :, c].std() + 1e-6
        ref_mu, ref_sd = ref_lab[:, :, c].mean(), ref_lab[:, :, c].std() + 1e-6
        transferred = (src_lab[:, :, c] - src_mu) * (ref_sd / src_sd) + ref_mu
        result[:, :, c] = src_lab[:, :, c] * (1.0 - s) + transferred * s

    return cv2.cvtColor(np.clip(result, 0, 255).astype(np.uint8), cv2.COLOR_LAB2RGB)


def _hue_shift_fallback(image: np.ndarray, name: str) -> np.ndarray:
    """Legacy hue-rotation + saturation scale when no reference image exists."""
    hsv = cv2.cvtColor(image, cv2.COLOR_RGB2HSV).astype(np.float32)
    hsv[:, :, 0] = (hsv[:, :, 0] + _HUE_SHIFT.get(name, 0)) % 180
    hsv[:, :, 1] = np.clip(hsv[:, :, 1] * _SAT_SCALE.get(name, 1.0), 0, 255)
    return cv2.cvtColor(hsv.astype(np.uint8), cv2.COLOR_HSV2RGB)


def _post_process(image: np.ndarray, params: dict) -> np.ndarray:
    """Brightness / contrast / grain / sharpness adjustments."""
    if not params:
        return image

    f = image.astype(np.float32) / 255.0
    brightness = params.get("brightness", 0.0)
    contrast   = params.get("contrast",   0.0)
    grain      = params.get("grain",      0.0)
    sharp      = params.get("sharp",      0.0)

    f = f * (1.0 + contrast) + brightness
    if grain > 0.0:
        f += np.random.normal(0.0, grain, f.shape).astype(np.float32)
    f = np.clip(f, 0.0, 1.0)
    out = (f * 255).astype(np.uint8)

    if sharp > 0.1:
        blurred = cv2.GaussianBlur(out, (0, 0), 3)
        out = cv2.addWeighted(out, 1.0 + sharp, blurred, -sharp, 0)
    elif sharp < -0.05:
        sigma = abs(sharp) * 6.0
        k = max(3, int(sigma * 2) | 1)
        out = cv2.GaussianBlur(out, (k, k), sigma)

    return out
